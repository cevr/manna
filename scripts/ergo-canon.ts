// Writes ergo/bible/canon.ergo from packages/core/src/bible/canon.ts: the 66
// books and the alias table the reference parser reads. Run after the canon
// changes:  bun scripts/ergo-canon.ts
// ParseIsTheReference (ergo/bible) fails when the two drift.
import { writeFile } from "node:fs/promises";
import { join } from "node:path";
import { BIBLE_BOOK_ALIASES, BIBLE_BOOKS } from "../packages/core/src/bible/canon";

const literal = (text: string) => JSON.stringify(text);
const books = BIBLE_BOOKS.map(
  (b) =>
    `\tBook{Number: ${b.number}, Name: ${literal(b.name)}, Abbreviation: ${literal(b.abbreviation)}, Chapters: ${b.chapters}, Testament: ${b.testament === "old" ? "Old" : "New"}},`,
);
const aliases = [...BIBLE_BOOK_ALIASES].map(([alias, n]) => `${literal(alias)}: ${n}`);
const source = `// Generated by scripts/ergo-canon.ts from packages/core/src/bible/canon.ts. Do not edit.

// Books is the canon in order; a book's Number is its index plus one.
let Books = []Book{
${books.join("\n")}
}

// aliases maps a lower-case alias to its book number.
let aliases = Map[string, int]{${aliases.join(", ")}}
`;
await writeFile(join(import.meta.dir, "../ergo/bible/canon.ergo"), source);
// The Go floor of Parse (floor/parse) reads the same alias table.
await writeFile(
  join(import.meta.dir, "../floor/parse/aliases.txt"),
  [...BIBLE_BOOK_ALIASES].map(([alias, n]) => `${alias}\t${n}\n`).join(""),
);
console.log(`wrote ${BIBLE_BOOKS.length} books and ${BIBLE_BOOK_ALIASES.size} aliases`);
